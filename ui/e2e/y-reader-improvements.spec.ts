import { expect, test } from "@playwright/test";

test("reader improvements: explicit navigation, source verification, dated history and responsive evidence", async ({page, request, context}) => {
  const response = await request.post(process.env.WIKICONTEXT_TEST_CONTROL + "/reader-navigation");
  expect(response.ok(), await response.text()).toBeTruthy();
  const fixture = await response.json();
  await page.setViewportSize({width:1440,height:1000});
  await page.goto("/#/page/spectroscopy");
  await page.getByText("Sign in with a password", {exact:true}).click();
  await page.getByLabel("Email", {exact:true}).fill("agent@example.com");
  await page.getByLabel("Password", {exact:true}).fill("SyntheticUserPassword123!");
  await page.getByRole("button", {name:"Sign in",exact:true}).click();
  await expect(page.getByRole("heading",{name:"Spectroscopy guide",exact:true})).toBeVisible();
  const history=page.getByLabel("Publication",{exact:true});
  await expect(history.locator('option[value="live"]')).toHaveText("Current version");
  expect(await history.locator('option').nth(1).innerText()).toMatch(/\d{4}/);
  await context.grantPermissions(['clipboard-read','clipboard-write']);
  await page.locator('.copy-links summary').click();
  await page.getByRole('button',{name:/This version/}).click();
  const copied=await page.evaluate(()=>navigator.clipboard.readText());
  expect(copied).toContain('publication=');
  await expect(page.locator('.copy-feedback')).toHaveText('Copied');
  await page.getByRole('button',{name:'Citation 1',exact:true}).click();
  await expect(page.locator('.evidence-panel')).toHaveAttribute('role','region');
  await expect(page.locator('.citation-claim-active')).toContainText('violet light');
  await page.screenshot({path:'/tmp/wikicontext-reader-evidence-desktop.png',fullPage:true});
  await page.getByRole('link',{name:'View in source',exact:true}).click();
  await expect(page).toHaveURL(new RegExp(`sources/${fixture.source}.*passage=${fixture.passage}`));
  await expect(page.locator('.source-content mark')).toContainText('spectroscopy instrument');
  await page.reload();
  await expect(page.locator('.source-content mark')).toContainText('violet light');
  await page.getByRole('button',{name:'Exact source',exact:true}).click();
  await expect(page.locator('.source-text')).toContainText('# Reviewed original');
  await page.goto(copied);
  await expect(page.getByRole('heading',{name:'Spectroscopy guide',exact:true})).toBeVisible();
  const selectedPublication=await history.inputValue();
  await page.getByRole('button',{name:'Citation 1',exact:true}).click();
  const sourceLink=page.getByRole('link',{name:'View in source',exact:true});
  expect(await sourceLink.getAttribute('href')).toContain(`publication=${selectedPublication}`);
  expect(await sourceLink.getAttribute('href')).toContain(`passage=${fixture.passage}`);
  await sourceLink.click();
  await expect(page.locator('.source-content mark')).toContainText('violet light');
  await history.selectOption('live');
  await expect(page).toHaveURL(new RegExp(`passage=${fixture.passage}`));
  await expect(page.locator('.source-content mark')).toContainText('violet light');
  await page.goto('/#/pages?topic=observing-science');
  await expect(page.locator('.directory-entries > li')).toHaveCount(1);
  await expect(page.locator('.directory-entries')).toContainText('Spectroscopy guide');
  await page.goto('/#/catalog/custom/instruments');
  await expect(page.getByRole('heading',{name:'Instruments',exact:true})).toBeVisible();
  await expect(page.locator('.custom-catalog')).toContainText('Synthetic laboratory');
  await page.goto('/#/welcome');
  await expect(page.getByText('Topics maintained in this publication.',{exact:true})).toBeVisible();
  await page.screenshot({path:'/tmp/wikicontext-reader-overview-dark.png',fullPage:true});
  await page.getByRole('button',{name:'Switch to light theme',exact:true}).click();
  await page.screenshot({path:'/tmp/wikicontext-reader-overview-light.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:'/tmp/wikicontext-reader-overview-mobile.png',fullPage:true});
  await page.setViewportSize({width:1440,height:1000});
  await history.selectOption((await history.locator('option').filter({hasText:/Publication 1$/}).getAttribute('value'))!);
  await expect(page.getByText(/Topics inferred from existing page titles/)).toBeVisible();
  await expect(page.getByRole('button',{name:/Observing science/})).toHaveCount(0);
  await page.goto('/#/page/spectroscopy');
  await page.getByLabel('Search pages',{exact:true}).fill('violet');
  await page.getByRole('region',{name:'Search results'}).getByRole('link',{name:/Spectroscopy guide/}).click();
  await expect(page.locator('.page-search-match')).toContainText('violet light');
  for(const width of [1000,390]) {
    await page.setViewportSize({width,height:844});
    await page.getByRole('button',{name:'Toggle navigation',exact:true}).click();
    await expect(page.getByRole('button',{name:'Close navigation',exact:true})).toBeFocused();
    await page.keyboard.press('Escape');
    await expect(page.getByRole('button',{name:'Toggle navigation',exact:true})).toBeFocused();
    await page.getByRole('button',{name:'Citation 1',exact:true}).click();
    await expect(page.locator('.evidence-panel')).toHaveAttribute('aria-modal','true');
    await page.keyboard.press('Escape');
    await expect(page.getByRole('button',{name:'Citation 1',exact:true})).toBeFocused();
    expect(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  }
});
